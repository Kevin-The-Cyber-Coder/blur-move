export function featureStats() {
  const all = FEATURE_GROUPS.flatMap(g => g.items);
  const done = all.filter(i => i.status === 'done').length;
  const partial = all.filter(i => i.status === 'partial').length;
  return { total: all.length, done, partial, planned: all.length - done - partial, pct: Math.round((done + partial * 0.5) / all.length * 100) };
}
